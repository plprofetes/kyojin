#!/usr/bin/env python3
"""Sprint/task tracker for the Windows port. The task files under doc/windows/sprints/ are the source of truth.

    python scripts/windows/tasks.py next            # first actionable task (not done, dependencies done), in priority order
    python scripts/windows/tasks.py list            # every task with status
    python scripts/windows/tasks.py set S1-02 active|blocked|done|dropped|todo   # edit the task file, then sync
    python scripts/windows/tasks.py sync            # regenerate the tables in the sprint READMEs and doc/windows/README.md
    python scripts/windows/tasks.py check           # validate links, dependencies, statuses, tables up to date (exit 1 on problems)

Layout:  doc/windows/sprints/s<N>-<slug>/README.md  (goal, exit criteria, generated task table)
         doc/windows/sprints/s<N>-<slug>/<NN>-<slug>.md  (one task; NN is the PRIORITY ORDER inside the sprint,
         hardest / most uncertain first so the project fails fast; ID = S<N>-<NN>)
A task file has bullet header lines "- Status:", "- Depends:" (IDs or "-"), "- Risk:". Stdlib only.
"""
from __future__ import annotations

import re
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DOCS = ROOT / "doc" / "windows"
STATUSES = ("todo", "active", "blocked", "done", "dropped")
START, END = "<!-- tasks:start (generated by scripts/windows/tasks.py sync; do not edit) -->", "<!-- tasks:end -->"
LINK = re.compile(r"(?<!\!)\[[^\]]*\]\(([^)\s]+)\)")


@dataclass
class Task:
    id: str
    sprint: int
    num: int
    title: str
    status: str
    depends: list[str]
    risk: str
    path: Path


@dataclass
class Sprint:
    n: int
    slug: str
    title: str
    dir: Path
    tasks: list[Task]


def _header(text: str, key: str) -> str:
    m = re.search(rf"^- {key}:[ \t]*(.*)$", text, re.M)
    return m.group(1).strip() if m else ""


def load(docs: Path = DOCS) -> list[Sprint]:
    sprints = []
    for d in sorted((docs / "sprints").glob("s[0-9]*-*")):
        n = int(re.match(r"s(\d+)-", d.name).group(1))
        readme = d / "README.md"
        title = re.search(r"^# (.+)$", readme.read_text(encoding="utf-8"), re.M).group(1) if readme.is_file() else d.name
        tasks = []
        for f in sorted(d.glob("[0-9][0-9]-*.md")):
            t = f.read_text(encoding="utf-8")
            num = int(f.name[:2])
            heading = re.search(r"^# (.+)$", t, re.M)
            deps = [x.strip() for x in re.split(r"[,\s]+", _header(t, "Depends")) if x.strip() and x.strip() != "-"]
            tasks.append(Task(f"S{n}-{num:02d}", n, num, heading.group(1) if heading else f.stem, _header(t, "Status"), deps,
                              _header(t, "Risk"), f))
        sprints.append(Sprint(n, d.name, title, d, tasks))
    return sprints


def all_tasks(sprints: list[Sprint]) -> list[Task]:
    return [t for s in sprints for t in s.tasks]


def next_task(sprints: list[Sprint]) -> Task | None:
    by_id = {t.id: t for t in all_tasks(sprints)}
    for t in all_tasks(sprints):
        if t.status in ("done", "dropped"):
            continue
        if all(by_id.get(d) is not None and by_id[d].status in ("done", "dropped") for d in t.depends):
            if t.status != "blocked":
                return t
    return None


def rel(from_file: Path, to: Path) -> str:
    return Path(__import__("os").path.relpath(to, from_file.parent)).as_posix()


def sprint_table(s: Sprint) -> str:
    if not s.tasks:
        return "_No task files yet (backlog; see the sprint text)._"
    rows = ["| Order | ID | Task | Status | Depends |", "|---|---|---|---|---|"]
    for t in s.tasks:
        rows.append(f"| {t.num} | {t.id} | [{t.title}]({t.path.name}) | {t.status} | {', '.join(t.depends) or '-'} |")
    return "\n".join(rows)


def overview_table(sprints: list[Sprint], readme: Path) -> str:
    rows = ["| Sprint | Status | Done | Link |", "|---|---|---|---|"]
    for s in sprints:
        done = sum(t.status in ("done", "dropped") for t in s.tasks)
        state = "no tasks yet" if not s.tasks else "done" if done == len(s.tasks) else "in progress" if any(t.status != "todo" for t in s.tasks) else "todo"
        rows.append(f"| S{s.n} {s.title} | {state} | {done}/{len(s.tasks)} | [{s.slug}]({rel(readme, s.dir / 'README.md')}) |")
    nt = next_task(sprints)
    rows.append("")
    rows.append(f"**Next actionable task:** [{nt.id} {nt.title}]({rel(readme, nt.path)}) (status: {nt.status})" if nt else "**Next actionable task:** none")
    return "\n".join(rows)


def _splice(text: str, body: str) -> str:
    block = f"{START}\n{body}\n{END}"
    if START in text and END in text:
        return re.sub(re.escape(START) + r".*?" + re.escape(END), lambda m: block, text, flags=re.S)
    return text.rstrip("\n") + "\n\n" + block + "\n"


def expected_files(sprints: list[Sprint], docs: Path) -> dict[Path, str]:
    out = {}
    top = docs / "README.md"
    if top.is_file():
        out[top] = _splice(top.read_text(encoding="utf-8"), overview_table(sprints, top))
    for s in sprints:
        r = s.dir / "README.md"
        if r.is_file():
            out[r] = _splice(r.read_text(encoding="utf-8"), sprint_table(s))
    return out


def sync(docs: Path = DOCS) -> list[Path]:
    changed = []
    for p, text in expected_files(load(docs), docs).items():
        if p.read_text(encoding="utf-8") != text:
            p.write_text(text, encoding="utf-8")
            changed.append(p)
    return changed


def check(docs: Path = DOCS) -> list[str]:
    problems = []
    sprints = load(docs)
    ids = {t.id: t for t in all_tasks(sprints)}
    seen = set()
    for t in all_tasks(sprints):
        if t.id in seen:
            problems.append(f"duplicate id {t.id}")
        seen.add(t.id)
        if t.status not in STATUSES:
            problems.append(f"{t.id}: bad status {t.status!r} (use {', '.join(STATUSES)})")
        for d in t.depends:
            if d not in ids:
                problems.append(f"{t.id}: unknown dependency {d}")
            elif d == t.id:
                problems.append(f"{t.id}: depends on itself")
        if not t.risk:
            problems.append(f"{t.id}: missing '- Risk:' line (why it is ordered here)")
    for f in sorted(docs.rglob("*.md")):
        for target in LINK.findall(f.read_text(encoding="utf-8")):
            if re.match(r"^[a-z]+:", target) or target.startswith("#") or "\\" in target or "|" in target:   # URLs, anchors, regex text
                continue
            path = target.split("#", 1)[0]
            if path and not (f.parent / path).resolve().exists():
                problems.append(f"{f.relative_to(docs.parent.parent)}: broken link {target}")
    for p, text in expected_files(sprints, docs).items():
        if p.read_text(encoding="utf-8") != text:
            problems.append(f"{p.relative_to(docs.parent.parent)}: generated table is stale (run: python scripts/windows/tasks.py sync)")
    return problems


def set_status(task_id: str, status: str, docs: Path = DOCS) -> Task:
    if status not in STATUSES:
        raise SystemExit(f"status must be one of {STATUSES}")
    t = next((x for x in all_tasks(load(docs)) if x.id == task_id), None)
    if t is None:
        raise SystemExit(f"unknown task {task_id}")
    text = t.path.read_text(encoding="utf-8")
    new, n = re.subn(r"^- Status:.*$", f"- Status: {status}", text, count=1, flags=re.M)
    if n != 1:
        raise SystemExit(f"{t.path}: no '- Status:' line")
    t.path.write_text(new, encoding="utf-8")
    sync(docs)
    return t


def main(argv: list[str]) -> int:
    cmd = argv[0] if argv else "next"
    sprints = load()
    if cmd == "list":
        for s in sprints:
            print(f"S{s.n} {s.title}")
            for t in s.tasks:
                print(f"  {t.id}  {t.status:<8} {t.title}   [{', '.join(t.depends) or '-'}]")
    elif cmd == "next":
        t = next_task(sprints)
        print(f"{t.id} {t.title}\n  status: {t.status}\n  file:   {t.path.relative_to(ROOT)}" if t else "no actionable task")
    elif cmd == "set" and len(argv) == 3:
        t = set_status(argv[1], argv[2])
        print(f"{t.id} -> {argv[2]}")
    elif cmd == "sync":
        for p in sync():
            print("updated", p.relative_to(ROOT))
    elif cmd == "check":
        probs = check()
        for p in probs:
            print("PROBLEM:", p)
        print("ok" if not probs else f"{len(probs)} problem(s)")
        return 1 if probs else 0
    else:
        print(__doc__)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
